// ---------- инлайн-разметка: **жирный**, ~~курсив~~ ----------
function runs(text, base = {}) {
  const out = [];
  const re = /(\*\*[^*]+\*\*|~~[^~]+~~)/g;
  let last = 0, m;
  while ((m = re.exec(text))) {
    if (m.index > last) out.push(new TextRun({ text: text.slice(last, m.index), ...base }));
    const t = m[0];
    if (t.startsWith('**')) out.push(new TextRun({ text: t.slice(2, -2), bold: true, ...base }));
    else out.push(new TextRun({ text: t.slice(2, -2), italics: true, ...base }));
    last = m.index + t.length;
  }
  if (last < text.length) out.push(new TextRun({ text: text.slice(last), ...base }));
  return out;
}

const body = [];
let figN = 0, tabN = 0;
const numRefs = [];

const H1 = (t, pageBreak = true) => body.push(new Paragraph({ heading: HeadingLevel.HEADING_1, pageBreakBefore: pageBreak, children: [new TextRun(t)] }));
const H2 = (t) => body.push(new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun(t)] }));
const H3 = (t) => body.push(new Paragraph({ heading: HeadingLevel.HEADING_3, children: [new TextRun(t)] }));
const P = (t, o = {}) => body.push(new Paragraph({ children: runs(t), spacing: { after: 120 }, alignment: o.align, keepNext: o.keepNext }));

function B(items, level = 0) {
  for (const it of items) {
    if (Array.isArray(it)) { B(it, level + 1); continue; }
    body.push(new Paragraph({ numbering: { reference: 'bullets', level }, children: runs(it), spacing: { after: 60 } }));
  }
}

function N(items) {
  const ref = 'num' + numRefs.length;
  numRefs.push(ref);
  for (const it of items) body.push(new Paragraph({ numbering: { reference: ref, level: 0 }, children: runs(it), spacing: { after: 60 } }));
}

function F(lines) {
  const L = Array.isArray(lines) ? lines : [lines];
  L.forEach((l, i) => body.push(new Paragraph({
    children: [new TextRun({ text: l, font: 'Consolas', size: 20, color: COL.ink })],
    shading: { type: ShadingType.CLEAR, fill: 'F3F5F8', color: 'auto' },
    border: { left: { style: BorderStyle.SINGLE, size: 18, color: '6D5BD0', space: 8 } },
    indent: { left: 160, right: 160 },
    spacing: { before: i === 0 ? 80 : 0, after: i === L.length - 1 ? 140 : 0 },
    keepNext: i < L.length - 1,
  })));
}

function Note(label, text, color = COL.teal, fill = 'E2F5F6') {
  body.push(new Paragraph({
    children: [new TextRun({ text: label + ' ', bold: true, color }), ...runs(text)],
    shading: { type: ShadingType.CLEAR, fill, color: 'auto' },
    border: { left: { style: BorderStyle.SINGLE, size: 24, color, space: 8 } },
    indent: { left: 160, right: 160 },
    spacing: { before: 100, after: 160 },
  }));
}

function Fig(name, caption) {
  figN++;
  const { W, H } = meta[name];
  const w = 640, h = Math.round(w * H / W);
  body.push(new Paragraph({ alignment: AlignmentType.CENTER, keepNext: true, spacing: { before: 120, after: 60 }, children: [new ImageRun({ type: 'png', data: fs.readFileSync(path.join(IMG, name + '.png')), transformation: { width: w, height: h } })] }));
  body.push(new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 200 }, children: [new TextRun({ text: `Рис. ${figN}. ${caption}`, italics: true, size: 20, color: COL.muted })] }));
}

const border = { style: BorderStyle.SINGLE, size: 4, color: COL.line };
const borders = { top: border, bottom: border, left: border, right: border, insideHorizontal: border, insideVertical: border };

function T(caption, headers, rows, widthsPct, o = {}) {
  tabN++;
  const widths = widthsPct.map((p) => Math.round(CW * p / 100));
  widths[widths.length - 1] = CW - widths.slice(0, -1).reduce((a, b) => a + b, 0);
  body.push(new Paragraph({ keepNext: true, spacing: { before: 120, after: 60 }, children: [new TextRun({ text: `Таблица ${tabN}. ${caption}`, bold: true, size: 20, color: COL.muted })] }));
  const cell = (txt, i, isHead, zebra) => new TableCell({
    width: { size: widths[i], type: WidthType.DXA },
    shading: { type: ShadingType.CLEAR, color: 'auto', fill: isHead ? COL.head : (zebra ? COL.zebra : 'FFFFFF') },
    margins: { top: 50, bottom: 50, left: 90, right: 90 },
    children: String(txt).split('\n').map((ln) => new Paragraph({
      spacing: { after: 0 },
      children: (o.mono && o.mono.includes(i) && !isHead)
        ? [new TextRun({ text: ln, font: 'Consolas', size: 18 })]
        : runs(ln, { size: 19, bold: isHead || undefined, color: isHead ? COL.ink : undefined }),
    })),
  });
  const trs = [new TableRow({ tableHeader: true, cantSplit: true, children: headers.map((h, i) => cell(h, i, true)) })];
  rows.forEach((r, ri) => trs.push(new TableRow({ cantSplit: true, children: r.map((c, i) => cell(c, i, false, ri % 2 === 1)) })));
  body.push(new Table({ width: { size: CW, type: WidthType.DXA }, columnWidths: widths, borders, rows: trs }));
  body.push(new Paragraph({ spacing: { after: 120 }, children: [] }));
}

